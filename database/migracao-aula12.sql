-- Migração para a aula 12 (FastAPI): o Python cria o lote e grava segmento, consultor e serviço
-- sem repetir; o Java não grava mais as linhas da planilha.
--
-- Só para um banco que já existia ANTES desta versão (um banco novo é criado certo pelo backend).
-- Rode UMA vez no DBeaver (ou no SQL Editor do Neon), com o backend DESLIGADO, e depois ligue o
-- backend novo. Se o banco veio de antes da aula 11, rode primeiro o migracao-aula11.sql.

BEGIN;

-- 1. A tabela de login passa a se chamar usuario (como no slide da aula 12).
DO $$
BEGIN
    IF to_regclass('public.usuarios') IS NOT NULL THEN
        -- o backend novo pode ter criado uma "usuario" vazia antes desta migração
        IF to_regclass('public.usuario') IS NOT NULL THEN
            IF EXISTS (SELECT 1 FROM usuario) THEN
                RAISE EXCEPTION 'As tabelas usuarios e usuario têm dados: confira antes de migrar.';
            END IF;
            DROP TABLE usuario;
        END IF;
        ALTER TABLE usuarios RENAME TO usuario;
    END IF;
END $$;

-- 2. Segmentos sem repetir, como consultor e serviço; o cliente passa a apontar para o segmento.
CREATE TABLE IF NOT EXISTS segmento (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome varchar(60) NOT NULL UNIQUE
);

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM information_schema.columns
               WHERE table_name = 'cliente' AND column_name = 'segmento') THEN
        INSERT INTO segmento (nome) SELECT DISTINCT segmento FROM cliente ON CONFLICT (nome) DO NOTHING;
        ALTER TABLE cliente ADD COLUMN IF NOT EXISTS segmento_id bigint;
        UPDATE cliente c SET segmento_id = s.id FROM segmento s WHERE s.nome = c.segmento AND c.segmento_id IS NULL;
        ALTER TABLE cliente DROP COLUMN segmento;
    END IF;
END $$;

ALTER TABLE cliente ALTER COLUMN segmento_id SET NOT NULL;
ALTER TABLE cliente DROP CONSTRAINT IF EXISTS fk_cliente_segmento;
ALTER TABLE cliente ADD CONSTRAINT fk_cliente_segmento FOREIGN KEY (segmento_id) REFERENCES segmento;

-- 3. O lote: quem cria é o Python, que não sabe quem enviou; entra a contagem de linhas com aviso.
ALTER TABLE upload_lote ADD COLUMN IF NOT EXISTS linhas_com_aviso integer NOT NULL DEFAULT 0;
ALTER TABLE upload_lote DROP COLUMN IF EXISTS enviado_por;

-- Só três situações agora: PROCESSANDO, PROCESSADO e ERRO.
UPDATE upload_lote SET status = 'ERRO', mensagem = 'Lote antigo que não chegou a ser processado.'
 WHERE status NOT IN ('PROCESSANDO', 'PROCESSADO', 'ERRO');
ALTER TABLE upload_lote DROP CONSTRAINT IF EXISTS upload_lote_status_check;
ALTER TABLE upload_lote ADD CONSTRAINT upload_lote_status_check CHECK (status IN ('PROCESSANDO', 'PROCESSADO', 'ERRO'));

-- 4. O Java não guarda mais as linhas da planilha: elas vão direto ao Python.
DROP TABLE IF EXISTS upload_linha;

COMMIT;

