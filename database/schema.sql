create table cliente (
    faturamento_anual numeric(15,2) not null,
    nivel char(1) not null check ((nivel in ('A','B','C'))),
    uf varchar(2),
    consultor_id bigint not null,
    id bigint generated by default as identity,
    lote_id bigint,
    segmento_id bigint not null,
    codigo_cti varchar(60) not null,
    cidade varchar(120),
    nome varchar(255) not null,
    primary key (id)
);

create table consultor (
    id bigint generated by default as identity,
    matricula varchar(20) unique,
    nome varchar(120) not null unique,
    primary key (id)
);

create table contrato (
    ativo boolean default true not null,
    data_contratacao date not null,
    cliente_id bigint not null,
    id bigint generated by default as identity,
    servico_id bigint not null,
    primary key (id)
);

create table estatistica_lote (
    gerado_em timestamp(6) not null,
    id bigint generated by default as identity,
    lote_id bigint not null unique,
    resultado text not null,
    primary key (id)
);

create table insights (
    faturamento_total numeric(17,2),
    quantidade_clientes integer,
    cliente_id bigint,
    contrato_id bigint,
    gerado_em timestamp(6) with time zone not null,
    id bigint generated by default as identity,
    faixa varchar(20) check ((faixa in ('MICRO','PEQUENA','MEDIA','GRANDE'))),
    classe varchar(30) not null check ((classe in ('ANALISE','FATURAMENTO','SEGMENTO'))),
    tipo varchar(30) not null,
    segmento varchar(60),
    titulo varchar(120),
    descricao varchar(1000),
    primary key (id)
);

create table segmento (
    id bigint generated by default as identity,
    nome varchar(60) not null unique,
    primary key (id)
);

create table servico (
    id bigint generated by default as identity,
    categoria varchar(30) default 'Outros' not null,
    nome varchar(120) not null unique,
    primary key (id)
);

create table telemetria (
    registros_processados integer,
    sucesso boolean not null,
    data_hora timestamp(6) not null,
    duracao_ms bigint,
    id bigint generated by default as identity,
    evento varchar(30) not null,
    mensagem varchar(500),
    primary key (id)
);

create table upload_lote (
    linhas_com_aviso integer not null,
    linhas_invalidas integer not null,
    linhas_validas integer not null,
    total_linhas integer not null,
    enviado_em timestamp(6) with time zone not null,
    id bigint generated by default as identity,
    status varchar(20) not null check ((status in ('PROCESSANDO','PROCESSADO','ERRO'))),
    mensagem varchar(500),
    arquivo_nome varchar(255) not null,
    primary key (id)
);

create table usuario (
    ativo boolean not null,
    consultor_id bigint unique,
    criado_em timestamp(6) with time zone not null,
    id bigint generated by default as identity,
    perfil varchar(20) default 'USER' not null check ((perfil in ('USER','ADMIN'))),
    status varchar(20) default 'APROVADO' not null check ((status in ('PENDENTE','APROVADO','BLOQUEADO'))),
    nome varchar(120) not null,
    email varchar(180) not null unique,
    senha varchar(255) not null,
    primary key (id)
);

