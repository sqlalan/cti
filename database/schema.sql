create table analises (
    avisos integer not null,
    clientes_atualizados integer not null,
    clientes_criados integer not null,
    linhas_lidas integer not null,
    linhas_rejeitadas integer not null,
    linhas_validas integer not null,
    gerado_em timestamp(6) with time zone not null,
    id bigint generated by default as identity,
    arquivo varchar(255) not null,
    indicadores jsonb not null,
    problemas jsonb not null,
    primary key (id)
);

create table clientes (
    faturamento_anual numeric(15,2) not null,
    nivel char(1) not null check ((nivel in ('A','B','C'))),
    uf varchar(2) not null,
    consultor_id bigint not null,
    id bigint generated by default as identity,
    codigo varchar(30) not null unique,
    segmento varchar(60) not null,
    cidade varchar(100) not null,
    nome varchar(160) not null,
    primary key (id)
);

create table consultores (
    id bigint generated by default as identity,
    matricula varchar(20) unique,
    nome varchar(120) not null unique,
    primary key (id)
);

create table contratos (
    data_contratacao date not null,
    cliente_id bigint not null,
    id bigint generated by default as identity,
    servico_id bigint not null,
    status varchar(20) default 'ATIVO' not null check ((status in ('ATIVO','CANCELADO'))),
    primary key (id)
);

create table insights (
    faturamento_total numeric(17,2),
    quantidade_clientes integer,
    analise_id bigint,
    cliente_id bigint,
    contrato_id bigint,
    gerado_em timestamp(6) with time zone not null,
    id bigint generated by default as identity,
    faixa varchar(20) check ((faixa in ('MICRO','PEQUENA','MEDIA','GRANDE'))),
    categoria varchar(30),
    tipo varchar(30) not null check ((tipo in ('ANALISE','FATURAMENTO','SEGMENTO'))),
    segmento varchar(60),
    titulo varchar(120),
    texto varchar(1000),
    primary key (id)
);

create table servicos (
    id bigint generated by default as identity,
    categoria varchar(20) default 'OUTROS' not null check ((categoria in ('CONECTIVIDADE','SEGURANCA','NUVEM','OUTROS'))),
    nome varchar(80) not null unique,
    primary key (id)
);

create table telemetria (
    registros_processados integer,
    sucesso boolean not null,
    duracao_ms bigint,
    id bigint generated by default as identity,
    ocorrido_em timestamp(6) with time zone not null,
    tipo_evento varchar(30) not null check ((tipo_evento in ('UPLOAD_PLANILHA','EXECUCAO_SCRIPT'))),
    detalhe varchar(500),
    primary key (id)
);

create table usuarios (
    ativo boolean not null,
    consultor_id bigint unique,
    criado_em timestamp(6) with time zone not null,
    id bigint generated by default as identity,
    perfil varchar(20) default 'USER' not null check ((perfil in ('USER','ADMIN'))),
    nome varchar(120) not null,
    email varchar(180) not null unique,
    senha varchar(255) not null,
    primary key (id)
);

